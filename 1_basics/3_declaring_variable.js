/**
 *  Variable 선언하기
 * 
 * 1) var - 더이상 쓰지 않는다.
 * 2) let
 * 3) const
 */
var name = '코드팩토리'; // 따옴표를 쓰면 글자 안 쓰면 변수
console.log(name);

var age = 22;
console.log(age);

let band = '밴드';
console.log(band);

/**
 * let과 var로 선언하면
 * 값을 추후 변경할 수 있다.
 */

band = 'ㅊㅈㅇ';
console.log(band);

const newJeans = '뉴진스';
console.log(newJeans);

// newJeans = '코드팩토리'; >>const는 값을 추후 변경할 수 X

